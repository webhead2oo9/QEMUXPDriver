"""XPDriver's version, from VERSION and the Git checkout.

MAJOR.MINOR.PATCH come from VERSION at the repository root; BUILD is the
number of commits reachable from HEAD (monotonic along the branch, the
same for every checkout of a commit; CI needs full history, not a shallow
clone). The commit is HEAD's short hash, "-dirty" when tracked files
differ from it. Without Git, XPD_BUILD and XPD_COMMIT supply them.

  version.py                 print MAJOR.MINOR.PATCH.BUILD
  version.py --full          print "MAJOR.MINOR.PATCH.BUILD (commit)"
  version.py --driverver     print an INF DriverVer: HEAD's commit date
                             (MM/DD/YYYY, reproducible), then the version
  version.py --header PATH   write a C/RC header with the XPD_VERSION_*
                             macros; untouched when its content is current
"""

import argparse
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def git(*args):
    try:
        return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                              capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def version():
    text = (ROOT / "VERSION").read_text(encoding="ascii").strip()
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", text)
    if not m or any(int(p) > 65535 for p in m.groups()):
        sys.exit(f"version.py: VERSION must be MAJOR.MINOR.PATCH, got {text!r}")
    build = git("rev-list", "--count", "HEAD") or os.environ.get("XPD_BUILD", "0")
    if not build.isdigit() or int(build) > 65535:
        sys.exit(f"version.py: build number {build!r} is not 0..65535")
    commit = git("rev-parse", "--short=10", "HEAD")
    if commit is None:
        commit = os.environ.get("XPD_COMMIT", "unknown")
    elif git("status", "--porcelain", "--untracked-files=no"):
        commit += "-dirty"
    date = git("log", "-1", "--format=%cd", "--date=format:%m/%d/%Y", "HEAD")
    return [int(p) for p in m.groups()] + [int(build)], commit, date


def header(parts, commit):
    dotted = ".".join(map(str, parts))
    return (
        "/* Generated by tools/version.py from VERSION and Git; do not edit. */\n"
        "#ifndef XPDRIVER_VERSION_H\n"
        "#define XPDRIVER_VERSION_H\n"
        f"#define XPD_VERSION_MAJOR {parts[0]}\n"
        f"#define XPD_VERSION_MINOR {parts[1]}\n"
        f"#define XPD_VERSION_PATCH {parts[2]}\n"
        f"#define XPD_VERSION_BUILD {parts[3]}\n"
        f"#define XPD_VERSION_RC {parts[0]},{parts[1]},{parts[2]},{parts[3]}\n"
        f'#define XPD_VERSION_STR "{dotted}"\n'
        f'#define XPD_VERSION_FULL "{dotted} ({commit})"\n'
        f'#define XPD_COMMIT_STR "{commit}"\n'
        "#endif\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--full", action="store_true")
    mode.add_argument("--driverver", action="store_true")
    mode.add_argument("--header", metavar="PATH")
    args = ap.parse_args()
    parts, commit, date = version()
    dotted = ".".join(map(str, parts))
    if args.header:
        out = pathlib.Path(args.header)
        text = header(parts, commit)
        if not out.exists() or out.read_text(encoding="ascii") != text:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="ascii", newline="\n")
    elif args.driverver:
        if date is None:
            sys.exit("version.py: --driverver needs Git for the commit date")
        print(f"{date},{dotted}")
    elif args.full:
        print(f"{dotted} ({commit})")
    else:
        print(dotted)


if __name__ == "__main__":
    main()

"""Writes xp_sp3_exports.txt: every named export of the Windows XP SP3 system
DLLs the QD3D guest binaries may import from, read from the DLLs themselves.

Usage: gen_xp_exports.py [--objdump OBJDUMP] --source TEXT DLL... > xp_sp3_exports.txt

The DLLs come from an XP SP3 x86 installation (e.g. extracted from the test
VM's System32) and are only read here: the output holds export names, not
code.  check_imports.py treats this list as the authority on what a guest
binary may import.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

EXPORT = re.compile(r"^\s*\[\s*\d+\]\s+\+base\[\s*\d+\]\s+[0-9a-f]{4}\s+(\S+)\s*$")


def exports(objdump, path):
    out = subprocess.run([objdump, "-p", path], check=True, capture_output=True, text=True).stdout
    names = []
    in_table = False
    for line in out.splitlines():
        if line.startswith("[Ordinal/Name Pointer] Table"):
            in_table = True
            continue
        if in_table:
            m = EXPORT.match(line)
            if m:
                names.append(m.group(1))
            elif names and not line.strip():
                break
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--objdump", default="i686-w64-mingw32-objdump")
    ap.add_argument("--source", required=True, help="where the DLLs came from, for the header")
    ap.add_argument("dll", nargs="+")
    args = ap.parse_args()

    out = sys.stdout
    out.write("# SPDX-License-Identifier: GPL-2.0-only\n")
    out.write("# Named exports of the Windows XP SP3 x86 system DLLs QD3D guest binaries may\n")
    out.write("# import from; the authority for check_imports.py.  Generated by\n")
    out.write("# gen_xp_exports.py from " + args.source + ":\n")
    for path in args.dll:
        with open(path, "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()
        out.write(f"#   {os.path.basename(path).lower()} sha256 {digest}\n")
    out.write("# Format: dll function\n")
    for path in args.dll:
        dll = os.path.basename(path).lower()
        names = exports(args.objdump, path)
        if not names:
            sys.exit(f"{path}: no named exports parsed")
        for name in sorted(set(names)):
            out.write(f"{dll} {name}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
